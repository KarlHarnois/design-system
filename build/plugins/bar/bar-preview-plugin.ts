import type { BuildHookOptions, Plugin } from "@terrazzo/parser";
import { ResolvedTheme } from "../shared/resolved-theme.ts";
import type { BarSpec } from "./bar-spec.ts";
import { BarStyle } from "./bar-style.ts";
import { SvgImage } from "./svg-image.ts";

const SVG_DATA_URL = "data:image/svg+xml,";
const HEADER = "// Generated by the design system from bar/bar.json. Do not edit.";

export class BarPreviewPlugin implements Plugin {
  readonly name = "bar-preview";
  private readonly spec: BarSpec;

  constructor(spec: BarSpec) {
    this.spec = spec;
  }

  build({ resolver, outputFile }: BuildHookOptions): void {
    const [style] = BarStyle.all(new ResolvedTheme(resolver.inputDefault, resolver));
    const globals = {
      BAR_SPEC: this.spec,
      BAR_IMAGES: this.imageDataUrls(),
      BAR_STYLE_PROPERTIES: style.properties(),
    };
    const assignments = Object.entries(globals).map(([name, value]) => `window.${name} = ${JSON.stringify(value, null, 2)};`);
    outputFile("bar/bar.js", `${HEADER}\n${assignments.join("\n")}\n`);
  }

  private imageDataUrls(): { [image: string]: { url: string; aspectRatio: number } } {
    return Object.fromEntries(this.spec.images().map((image) => [image, this.preview(this.spec.imageSource(image))]));
  }

  private preview(source: string): { url: string; aspectRatio: number } {
    return { url: `${SVG_DATA_URL}${encodeURIComponent(source)}`, aspectRatio: new SvgImage(source).aspectRatio() };
  }
}
