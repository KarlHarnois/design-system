import type { Plugin } from "@terrazzo/parser";
import type { BuildHookOptions } from "@terrazzo/parser";
import type { BarSpec } from "./bar-spec.ts";

const HEADER = "// Generated by the design system from bar/bar.json. Do not edit.";

export class BarPreviewPlugin implements Plugin {
  readonly name = "bar-preview";
  private readonly spec: BarSpec;

  constructor(spec: BarSpec) {
    this.spec = spec;
  }

  build({ outputFile }: BuildHookOptions): void {
    outputFile("bar/bar.js", `${HEADER}\nwindow.BAR_SPEC = ${JSON.stringify(this.spec, null, 2)};\n`);
  }
}
