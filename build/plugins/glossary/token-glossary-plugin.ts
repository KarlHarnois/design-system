import type { BuildHookOptions, Plugin } from "@terrazzo/parser";
import { ResolvedTheme } from "../shared/resolved-theme.ts";
import { TokenGlossary } from "./token-glossary.ts";

const HEADER = "// Generated by the design system from tokens/. Do not edit.";

export class TokenGlossaryPlugin implements Plugin {
  readonly name = "token-glossary";
  private readonly themeNames: string[];

  constructor(themeNames: string[]) {
    this.themeNames = themeNames;
  }

  build({ resolver, outputFile }: BuildHookOptions): void {
    const themes = this.themeNames.map((themeName) => new ResolvedTheme({ theme: themeName }, resolver));
    const entries = JSON.stringify(new TokenGlossary(themes).entries(), null, 2);
    outputFile("glossary/glossary.json", `${entries}\n`);
    outputFile("glossary/glossary.js", `${HEADER}\nwindow.TOKEN_GLOSSARY = ${entries};\n`);
  }
}
