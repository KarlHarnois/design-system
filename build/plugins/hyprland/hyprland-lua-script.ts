import type { HyprlandSettingsJson, LuaValue } from "./hyprland-settings.ts";

const HEADER = "-- Generated by the design system. Do not edit.";
const INDENT = "  ";
const LUA_IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/;

export class HyprlandLuaScript {
  private readonly settings: HyprlandSettingsJson;

  constructor(settings: HyprlandSettingsJson) {
    this.settings = settings;
  }

  render(): string {
    const curves = this.settings.curve.map((curve) => HyprlandLuaScript.call("curve", curve._args));
    const config = HyprlandLuaScript.call("config", [this.settings.config]);
    const animations = this.settings.animation.map((animation) => HyprlandLuaScript.call("animation", [animation]));
    return [HEADER, ...curves, config, ...animations].join("\n").concat("\n");
  }

  private static call(functionName: string, args: LuaValue[]): string {
    return `hl.${functionName}(${args.map((arg) => HyprlandLuaScript.literal(arg, "")).join(", ")})`;
  }

  private static literal(value: LuaValue, indent: string): string {
    if (typeof value === "string") return JSON.stringify(value);
    if (typeof value !== "object") return String(value);
    if (Array.isArray(value)) return `{ ${value.map((item) => HyprlandLuaScript.literal(item, indent)).join(", ")} }`;
    return HyprlandLuaScript.table(value, indent);
  }

  private static table(fields: { [key: string]: LuaValue }, indent: string): string {
    const inner = indent + INDENT;
    const lines = Object.entries(fields).map(
      ([key, value]) => `${inner}${HyprlandLuaScript.key(key)} = ${HyprlandLuaScript.literal(value, inner)},`,
    );
    return `{\n${lines.join("\n")}\n${indent}}`;
  }

  private static key(name: string): string {
    return LUA_IDENTIFIER.test(name) ? name : `[${JSON.stringify(name)}]`;
  }
}
