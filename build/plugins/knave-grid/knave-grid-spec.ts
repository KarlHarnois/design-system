import type { ResolvedTheme } from "../shared/resolved-theme.ts";
import { GridFont } from "./grid-font.ts";
import { GridTypeStyle } from "./grid-type-style.ts";

const BODY_STYLE_ID = "type.ui";
const FONT_FAMILY_GROUP = "font.family";
const TYPE_STYLE_GROUP = "type";
const TYPE_AREA_GROUP = "grid.type-area";

export class KnaveGridSpec {
  private readonly tokens: ResolvedTheme;
  private readonly fontDirectory: string;
  private readonly body: GridTypeStyle;
  private readonly styles: GridTypeStyle[];
  private readonly fonts: GridFont[];

  constructor(tokens: ResolvedTheme, fontDirectory: string) {
    this.tokens = tokens;
    this.fontDirectory = fontDirectory;
    this.body = new GridTypeStyle("ui", tokens.typography(BODY_STYLE_ID));
    this.styles = this.typeStyles();
    this.fonts = this.usedFonts();
  }

  render(): string {
    return `; Generated by the knave-grid Terrazzo plugin from tokens/. Edit the tokens instead.

(use knave-grid defgrid)

(export design-grid)

(defgrid design-grid ()
  (fonts :from "${this.fontDirectory}"
         ${this.fonts.map((font) => font.clause()).join("\n         ")})
  (body ${this.fontOf(this.body).name} :size ${KnaveGridSpec.float(this.body.sizePx)} :line-height ${this.body.leadingPx / this.body.sizePx})
  (type-areas ${this.typeAreaClauses().join("\n              ")})
  (type-styles ${this.styles.map((style) => this.typeStyleClause(style)).join("\n               ")}))
`;
  }

  private typeStyles(): GridTypeStyle[] {
    return this.tokens
      .idsUnder(TYPE_STYLE_GROUP)
      .filter((id) => id !== BODY_STYLE_ID)
      .map((id) => new GridTypeStyle(KnaveGridSpec.lastSegment(id), this.tokens.typography(id)));
  }

  private usedFonts(): GridFont[] {
    const fonts = this.tokens
      .idsUnder(FONT_FAMILY_GROUP)
      .map((id) => new GridFont(KnaveGridSpec.lastSegment(id), this.tokens.fontFamilyNames(id)));
    for (const style of [this.body, ...this.styles]) {
      KnaveGridSpec.fontAmong(fonts, style).addWeight(style.weight);
    }
    return fonts.filter((font) => font.isUsed());
  }

  private typeStyleClause(style: GridTypeStyle): string {
    const lines = style.lines(this.body.leadingPx);
    const fields = [`:lines ${lines}`, `:weight ${style.weight}`];
    if (style.sizePx !== lines * this.body.sizePx) fields.push(`:size ${KnaveGridSpec.float(style.sizePx)}`);
    if (!style.usesFamily(this.body.fontFamily)) fields.push(`:font-family ${this.fontOf(style).name}`);
    if (lines === 1) fields.push(":baseline-line 1");
    return `(${style.name} ${fields.join(" ")})`;
  }

  private typeAreaClauses(): string[] {
    return this.typeAreaNames()
      .map((name) => ({ name, field: (field: string) => this.tokens.number(`${TYPE_AREA_GROUP}.${name}.${field}`) }))
      .sort((narrower, wider) => narrower.field("width") - wider.field("width"))
      .map(({ name, field }) => `(${name} :width ${field("width")} :column-count ${field("column-count")} :margin ${field("margin")})`);
  }

  private typeAreaNames(): string[] {
    const names = this.tokens.idsUnder(TYPE_AREA_GROUP).map((id) => id.split(".").at(-2) ?? "");
    return [...new Set(names)];
  }

  private fontOf(style: GridTypeStyle): GridFont {
    return KnaveGridSpec.fontAmong(this.fonts, style);
  }

  private static fontAmong(fonts: GridFont[], style: GridTypeStyle): GridFont {
    const font = fonts.find((candidate) => style.usesFamily(candidate.fontFamily));
    if (font === undefined) {
      throw new Error(`Type style "${style.name}" uses a font family that no ${FONT_FAMILY_GROUP} token defines`);
    }
    return font;
  }

  private static lastSegment(id: string): string {
    return id.split(".").at(-1) ?? id;
  }

  private static float(value: number): string {
    return Number.isInteger(value) ? `${value}.0` : `${value}`;
  }
}
