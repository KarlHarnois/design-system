import type { ResolvedTheme } from "../shared/resolved-theme.ts";

const HEADER = "// Generated by the design system. Do not edit.";
const LOW_BATTERY_BELOW_PERCENT = 10;
const DATE_FORMAT = "{:%a %d %b}";
const TIME_FORMAT = "{:%H:%M}";
const TITLE_ALIGNED_LEFT = 0;

type WaybarConfigJson = { [key: string]: unknown };

export class WaybarConfig {
  private readonly theme: ResolvedTheme;

  constructor(theme: ResolvedTheme) {
    this.theme = theme;
  }

  render(): string {
    return `${HEADER}\n${JSON.stringify(this.toJSON(), null, 2)}\n`;
  }

  toJSON(): WaybarConfigJson {
    const frame = this.theme.pixels("space.frame");
    return {
      layer: "top",
      position: "top",
      height: this.outerHeight(),
      "margin-top": frame,
      "margin-right": frame,
      "margin-left": frame,
      spacing: 0,
      "fixed-center": false,
      "expand-center": true,
      "modules-left": ["hyprland/workspaces", "hyprland/submap"],
      "modules-center": ["hyprland/window"],
      "modules-right": ["pulseaudio", "battery", "clock#date", "clock#time"],
      "hyprland/window": { format: "{title}", expand: true, align: TITLE_ALIGNED_LEFT },
      pulseaudio: { format: "vol {volume:>3}%", "format-muted": "vol  ---" },
      battery: {
        format: "bat {capacity:>3}%",
        "format-charging": "chg {capacity:>3}%",
        states: { critical: LOW_BATTERY_BELOW_PERCENT - 1 },
      },
      "clock#date": { format: DATE_FORMAT },
      "clock#time": { format: TIME_FORMAT },
    };
  }

  private outerHeight(): number {
    const inset = this.theme.pixels("space.inset");
    const outline = this.theme.pixels("border.width.default");
    return this.theme.pixels("bar.height") + 2 * inset + 2 * outline;
  }
}
