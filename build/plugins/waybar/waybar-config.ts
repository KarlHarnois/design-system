import type { BarSpec } from "../bar/bar-spec.ts";
import type { ResolvedTheme } from "../shared/resolved-theme.ts";
import { WaybarModule } from "./waybar-module.ts";

const HEADER = "// Generated by the design system from bar/bar.json. Do not edit.";

type WaybarConfigJson = { [key: string]: unknown };

export class WaybarConfig {
  private readonly theme: ResolvedTheme;
  private readonly spec: BarSpec;

  constructor(theme: ResolvedTheme, spec: BarSpec) {
    this.theme = theme;
    this.spec = spec;
  }

  render(): string {
    return `${HEADER}\n${JSON.stringify(this.toJSON(), null, 2)}\n`;
  }

  toJSON(): WaybarConfigJson {
    const frame = this.theme.pixels("space.frame");
    return {
      layer: "top",
      position: "top",
      height: this.outerHeight(),
      "margin-top": frame,
      "margin-right": frame,
      "margin-left": frame,
      spacing: 0,
      "modules-left": this.spec.left.flatMap((group) => group.modules.map((module) => module.waybar)),
      "modules-right": this.spec.right.flatMap((group) => group.modules.map((module) => module.waybar)),
      ...this.moduleSettings(),
    };
  }

  private moduleSettings(): WaybarConfigJson {
    const modules = this.spec.modules().map((module) => new WaybarModule(module));
    return Object.fromEntries(modules.map((module) => [module.name, module.settings()]));
  }

  private outerHeight(): number {
    const inset = this.theme.pixels("space.inset");
    const outline = this.theme.pixels("border.width.default");
    return this.theme.pixels("bar.line") + 2 * inset + 2 * outline;
  }
}
