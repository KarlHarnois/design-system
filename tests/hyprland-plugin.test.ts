import { beforeAll, describe, expect, it } from "vitest";
import { HyprlandPlugin } from "../build/plugins/hyprland/hyprland-plugin.ts";
import { FixtureBuild } from "./support/fixture-build.ts";

describe("HyprlandPlugin", () => {
  let fixtureBuild: FixtureBuild;

  beforeAll(async () => {
    fixtureBuild = await FixtureBuild.run(new HyprlandPlugin(["dark", "light"]));
  });

  const settings = (theme: string) => JSON.parse(fixtureBuild.file(`hyprland/${theme}/settings.json`));

  it("marks the Lua theme as generated", () => {
    expect(fixtureBuild.file("hyprland/dark/theme.lua")).toMatch(/^-- Generated by the design system\. Do not edit\./);
  });

  it("splits the cell gutter across neighbouring window sides", () => {
    expect(settings("dark").config.general.gaps_in).toEqual({ top: 2, right: 3, bottom: 3, left: 2 });
  });

  it("frames the screen edge with the frame space, leaving one gutter under the floating bar", () => {
    expect(settings("dark").config.general.gaps_out).toEqual({ top: 5, right: 12, bottom: 12, left: 12 });
  });

  it("draws borders at the default border width", () => {
    expect(settings("dark").config.general.border_size).toBe(2);
  });

  it("outlines the focused window in the focus color", () => {
    expect(settings("dark").config.general.col.active_border).toBe("rgb(ff0000)");
  });

  it("outlines other windows in the default border color per theme", () => {
    expect(settings("light").config.general.col.inactive_border).toBe("rgb(bfbfbf)");
  });

  it("rounds containers with the container radius", () => {
    expect(settings("dark").config.decoration.rounding).toBe(6);
  });

  it("converts the quick duration to Hyprland speed in tenths of a second", () => {
    expect(settings("dark").animation).toContainEqual({ leaf: "fade", enabled: true, speed: 2.5, bezier: "ease-out" });
  });

  it("opens and closes windows without a pop or a fade", () => {
    expect(settings("dark").animation).toEqual(
      expect.arrayContaining(["windowsIn", "windowsOut", "fadeIn", "fadeOut"].map((leaf) => ({ leaf, enabled: false }))),
    );
  });

  it("turns off opening and closing after enabling fades, so the fade does not reach them", () => {
    const leaves = settings("dark").animation.map((animation: { leaf: string }) => animation.leaf);
    expect(leaves.indexOf("fadeIn")).toBeGreaterThan(leaves.indexOf("fade"));
  });

  it("makes window and workspace changes instant", () => {
    expect(settings("dark").animation).toContainEqual({ leaf: "workspaces", enabled: false });
  });

  it("calls the Hyprland Lua API with the same settings", () => {
    expect(fixtureBuild.file("hyprland/dark/theme.lua")).toContain('hl.animation({\n  leaf = "windowsMove",');
  });
});
