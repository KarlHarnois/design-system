import { beforeAll, describe, expect, it } from "vitest";
import type { GlossaryEntry } from "../build/plugins/glossary/token-glossary.ts";
import { TokenGlossaryPlugin } from "../build/plugins/glossary/token-glossary-plugin.ts";
import { FixtureBuild } from "./support/fixture-build.ts";

describe("TokenGlossaryPlugin", () => {
  let fixtureBuild: FixtureBuild;

  beforeAll(async () => {
    fixtureBuild = await FixtureBuild.run(new TokenGlossaryPlugin(["dark", "light"]));
  });

  const entry = (id: string): GlossaryEntry | undefined =>
    JSON.parse(fixtureBuild.file("glossary/glossary.json")).find((candidate: GlossaryEntry) => candidate.id === id);

  it("lists a value per theme", () => {
    expect(entry("color.text.primary")?.values).toEqual({ dark: "#ffffff", light: "#000000" });
  });

  it("names the CSS variable", () => {
    expect(entry("space.cell")?.cssVariable).toBe("--space-cell");
  });

  it("names the token an alias points at", () => {
    expect(entry("space.gutter")?.aliasOf).toBe("space.cell");
  });

  it("keeps the description", () => {
    expect(entry("space.gutter")?.description).toBe("Space between columns.");
  });

  it("summarises typography as size, line height, family and weight", () => {
    expect(entry("type.ui")?.values.dark).toBe("10px/1.5 Fixture Mono 400");
  });

  it("sorts numbered tokens by number", () => {
    const ids = JSON.parse(fixtureBuild.file("glossary/glossary.json")).map((candidate: GlossaryEntry) => candidate.id);

    expect(ids.indexOf("color.gray.200")).toBeLessThan(ids.indexOf("color.gray.1000"));
  });

  it("publishes the glossary to the specimen as a script", () => {
    expect(fixtureBuild.file("glossary/glossary.js")).toMatch(/^\/\/ Generated by the design system.*\nwindow\.TOKEN_GLOSSARY = \[/);
  });
});
