import { beforeAll, describe, expect, it } from "vitest";
import { BarSpec } from "../build/plugins/bar/bar-spec.ts";
import { WaybarPlugin } from "../build/plugins/waybar/waybar-plugin.ts";
import { FixtureBuild } from "./support/fixture-build.ts";

describe("WaybarPlugin", () => {
  let fixtureBuild: FixtureBuild;

  beforeAll(async () => {
    fixtureBuild = await FixtureBuild.run(new WaybarPlugin(["dark", "light"], BarSpec.read(new URL("fixtures/bar.json", import.meta.url).pathname)));
  });

  const stylesheet = () => fixtureBuild.file("waybar/dark/style.css");

  it("defines each color token as a GTK hex color", () => {
    expect(fixtureBuild.file("waybar/dark/colors.css")).toContain("@define-color color_surface_base #000000;");
  });

  it("resolves colors per theme", () => {
    expect(fixtureBuild.file("waybar/light/colors.css")).toContain("@define-color color_surface_base #ffffff;");
  });

  it("sets the whole bar in the small type family", () => {
    expect(stylesheet()).toContain('font-family: "Fixture Wide", monospace;');
  });

  it("sets the whole bar in the small type size", () => {
    expect(stylesheet()).toContain("font-size: 8px;");
  });

  it("makes each label one bar line tall", () => {
    expect(stylesheet()).toMatch(/label,\nbutton \{\n {2}min-height: 18px;/);
  });

  it("outlines the bar in the default border color", () => {
    expect(stylesheet()).toContain("border: 2px solid @color_border_default;");
  });

  it("insets the bar content evenly on all four sides", () => {
    expect(stylesheet()).toMatch(/window#waybar > box \{[^}]*\n {2}padding: 3px;\n\}/);
  });

  it("pads each workspace by the marker padding", () => {
    expect(stylesheet()).toMatch(/#workspaces button \{\n {2}padding: 0 4px;/);
  });

  it("makes a workspace at least as wide as the bar line, counting GTK's content box", () => {
    expect(stylesheet()).toMatch(/#workspaces button \{[^}]*\n {2}min-width: 10px;/);
  });

  it("spaces workspaces the marker padding apart", () => {
    expect(stylesheet()).toMatch(/#workspaces button \{[^}]*\n {2}margin-right: 4px;/);
  });

  it("drops the trailing margin after the last workspace", () => {
    expect(stylesheet()).toContain("#workspaces button:last-child {\n  margin-right: 0;");
  });

  it("spaces modules in a group a cell apart, without a trailing margin", () => {
    expect(stylesheet()).toContain("#pulseaudio {\n  margin-right: 5px;");
  });

  it("spaces groups a group space apart, without a trailing margin", () => {
    expect(stylesheet()).toContain("box#status {\n  margin-right: 10px;");
  });

  it("rounds the bar with the container radius", () => {
    expect(stylesheet()).toContain("border-radius: 6px;");
  });

  it("inverts the current workspace on the focus color", () => {
    expect(stylesheet()).toMatch(/#workspaces button\.active \{\n {2}background: @color_focus;\n {2}color: @color_text_inverse;/);
  });

  it("pads every module except the workspaces by the control padding", () => {
    expect(stylesheet()).toContain("#pulseaudio,\n#battery,\n#clock.time {\n  padding: 0 6px;");
  });

  it("sets the time in the primary text color", () => {
    expect(stylesheet()).toMatch(/#clock\.time \{\n {2}color: @color_text_primary;/);
  });

  const config = () => JSON.parse(fixtureBuild.file("waybar/dark/settings.json"));

  it("marks the Waybar config as generated", () => {
    expect(fixtureBuild.file("waybar/dark/config.jsonc")).toMatch(/^\/\/ Generated by the design system from bar\/bar\.json\. Do not edit\./);
  });

  it("writes the same settings into the Waybar config", () => {
    expect(fixtureBuild.file("waybar/dark/config.jsonc")).toContain('"modules-right": [\n    "group/status",\n    "clock#time"\n  ]');
  });

  it("makes the bar one bar line tall plus its inset and outline", () => {
    expect(config().height).toBe(28);
  });

  it("floats the bar inside the frame on the top, left and right", () => {
    expect(config()).toMatchObject({ "margin-top": 12, "margin-right": 12, "margin-left": 12 });
  });

  it("lists the groups of each side in the spec's order", () => {
    expect(config()["modules-right"]).toEqual(["group/status", "clock#time"]);
  });

  it("lays out each group's modules in a row", () => {
    expect(config()["group/status"]).toEqual({ orientation: "inherit", modules: ["pulseaudio", "battery"] });
  });

  it("writes a state's own format", () => {
    expect(config().battery["format-critical"]).toBe("power {capacity:02}%");
  });

  it("keeps the spec's format for each module", () => {
    expect(config().battery.format).toBe("power {capacity}%");
  });

  it("writes each spec variant as a Waybar format", () => {
    expect(config().battery["format-charging"]).toBe("plug {capacity}%");
  });

  it("fixes the module width with a minimum length", () => {
    expect(config().battery["min-length"]).toBe(10);
  });

  it("right-aligns the text inside the fixed width", () => {
    expect(config().battery.align).toBe(1);
  });

  it("turns a below threshold into Waybar's at-or-below state", () => {
    expect(config().battery.states).toEqual({ critical: 19 });
  });

  it("shrinks a critical battery's inverted padding to the marker padding and keeps its footprint", () => {
    expect(stylesheet()).toMatch(/#battery\.critical:not\(\.charging\) \{\n {2}padding: 0 4px;\n {2}margin: 0 2px;/);
  });

  it("inverts a critical battery unless it is charging", () => {
    expect(stylesheet()).toContain("#battery.critical:not(.charging) {");
  });
});
