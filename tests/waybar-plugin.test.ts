import { beforeAll, describe, expect, it } from "vitest";
import { BarSpec } from "../build/plugins/bar/bar-spec.ts";
import { WaybarPlugin } from "../build/plugins/waybar/waybar-plugin.ts";
import { FixtureBuild } from "./support/fixture-build.ts";

describe("WaybarPlugin", () => {
  let fixtureBuild: FixtureBuild;

  beforeAll(async () => {
    fixtureBuild = await FixtureBuild.run(new WaybarPlugin(["dark", "light"], BarSpec.read(new URL("fixtures/bar.json", import.meta.url).pathname)));
  });

  const stylesheet = () => fixtureBuild.file("waybar/dark/floating/style.css");

  it("defines each color token as a GTK hex color", () => {
    expect(fixtureBuild.file("waybar/dark/floating/colors.css")).toContain("@define-color color_surface_base #000000;");
  });

  it("defines an alias as a reference, so overriding the aliased color reaches it", () => {
    expect(fixtureBuild.file("waybar/dark/floating/colors.css")).toContain(
      "@define-color component_bar_style_floating_marker @color_focus;",
    );
  });

  it("resolves colors per theme", () => {
    expect(fixtureBuild.file("waybar/light/floating/colors.css")).toContain("@define-color color_surface_base #ffffff;");
  });

  it("sets the whole bar in the small type family", () => {
    expect(stylesheet()).toContain('font-family: "Fixture Wide", monospace;');
  });

  it("sets the whole bar in the small type size", () => {
    expect(stylesheet()).toContain("font-size: 8px;");
  });

  it("makes each label one bar line tall", () => {
    expect(stylesheet()).toMatch(/label,\nbutton \{\n {2}min-height: 18px;/);
  });

  it("outlines the bar in its style's outline width and colour", () => {
    expect(stylesheet()).toContain("border: 2px solid @component_bar_style_floating_outline;");
  });

  it("insets the bar content evenly on all four sides", () => {
    expect(stylesheet()).toMatch(/window#waybar > box \{[^}]*\n {2}padding: 3px;\n\}/);
  });

  it("pads each workspace by the marker padding", () => {
    expect(stylesheet()).toMatch(/#workspaces button \{\n {2}padding: 0 4px;/);
  });

  it("makes a workspace at least as wide as the bar line, counting GTK's content box", () => {
    expect(stylesheet()).toMatch(/#workspaces button \{[^}]*\n {2}min-width: 10px;/);
  });

  it("spaces workspaces the marker padding apart", () => {
    expect(stylesheet()).toMatch(/#workspaces button \{[^}]*\n {2}margin-right: 4px;/);
  });

  it("drops the trailing margin after the last workspace", () => {
    expect(stylesheet()).toContain("#workspaces button:last-child {\n  margin-right: 0;");
  });

  it("spaces modules in a group a cell apart, without a trailing margin", () => {
    expect(stylesheet()).toContain("#pulseaudio {\n  margin-right: 5px;");
  });

  it("spaces groups a group space apart, without a trailing margin", () => {
    expect(stylesheet()).toContain("box#status {\n  margin-right: 10px;");
  });

  it("rounds the bar with the container radius", () => {
    expect(stylesheet()).toContain("border-radius: 6px;");
  });

  it("inverts the current workspace on its style's marker colours", () => {
    expect(stylesheet()).toMatch(
      /#workspaces button\.active \{\n {2}background: @component_bar_style_floating_marker;\n {2}color: @component_bar_style_floating_marker_text;/,
    );
  });

  it("gives every marker module the marker padding, so inverting it changes only its colours", () => {
    expect(stylesheet()).toContain("#pulseaudio,\n#battery {\n  padding: 0 4px;");
  });

  it("gives a module that never becomes a marker its style's plain padding", () => {
    expect(stylesheet()).toContain("#clock.time {\n  padding: 0 4px;");
  });

  it("sets the time in its style's emphasis colour", () => {
    expect(stylesheet()).toMatch(/#clock\.time \{\n {2}color: @component_bar_style_floating_emphasis;/);
  });

  const config = () => JSON.parse(fixtureBuild.file("waybar/dark/floating/settings.json"));

  it("marks the Waybar config as generated", () => {
    expect(fixtureBuild.file("waybar/dark/floating/config.jsonc")).toMatch(/^\/\/ Generated by the design system from bar\/bar\.json\. Do not edit\./);
  });

  it("writes the same settings into the Waybar config", () => {
    expect(fixtureBuild.file("waybar/dark/floating/config.jsonc")).toContain('"modules-right": [\n    "group/status",\n    "clock#time"\n  ]');
  });

  it("makes the bar one bar line tall plus its inset and outline", () => {
    expect(config().height).toBe(28);
  });

  it("floats the bar inside the frame on the top, left and right", () => {
    expect(config()).toMatchObject({ "margin-top": 12, "margin-right": 12, "margin-left": 12 });
  });

  it("lists the groups of each side in the spec's order", () => {
    expect(config()["modules-right"]).toEqual(["group/status", "clock#time"]);
  });

  it("lays out each group's modules in a row", () => {
    expect(config()["group/status"]).toEqual({ orientation: "inherit", modules: ["pulseaudio", "battery"] });
  });

  it("writes the spec's icons as Waybar format icons", () => {
    expect(config()["hyprland/workspaces"]).toEqual({ format: "{icon}", "format-icons": { "10": "0" } });
  });

  it("writes a state's own format", () => {
    expect(config().battery["format-critical"]).toBe("power {capacity:02}%");
  });

  it("keeps the spec's format for each module", () => {
    expect(config().battery.format).toBe("power {capacity}%");
  });

  it("writes each spec variant as a Waybar format", () => {
    expect(config().battery["format-charging"]).toBe("plug {capacity}%");
  });

  it("fixes the module width with a minimum length", () => {
    expect(config().battery["min-length"]).toBe(10);
  });

  it("right-aligns the text inside the fixed width", () => {
    expect(config().battery.align).toBe(1);
  });

  it("turns a below threshold into Waybar's at-or-below state", () => {
    expect(config().battery.states).toEqual({ critical: 19 });
  });

  it("changes only the colours of a critical battery, never its size", () => {
    expect(stylesheet()).toMatch(
      /#battery\.critical:not\(\.charging\) \{\n {2}background: @component_bar_style_floating_marker;\n {2}color: @component_bar_style_floating_marker_text;\n\}/,
    );
  });

  it("inverts a critical battery unless it is charging", () => {
    expect(stylesheet()).toContain("#battery.critical:not(.charging) {");
  });

  describe("borderless", () => {
    const borderlessStylesheet = () => fixtureBuild.file("waybar/dark/borderless/style.css");
    const borderlessConfig = () => JSON.parse(fixtureBuild.file("waybar/dark/borderless/settings.json"));
    const borderlessBox = () => borderlessStylesheet().match(/window#waybar > box \{[^}]*\}/)?.[0];

    it("makes the bar exactly one bar line tall", () => {
      expect(borderlessConfig().height).toBe(18);
    });

    it("sets the text where the floating bar's outline and inset put it", () => {
      expect(borderlessConfig()["margin-top"]).toBe(5);
    });

    it("sets the bar inside the frame on the left and right, like a row of windows", () => {
      expect(borderlessConfig()).toMatchObject({ "margin-right": 12, "margin-left": 12 });
    });

    it("drops the plain padding, so the time meets the window edge", () => {
      expect(borderlessStylesheet()).toContain("#clock.time {\n  padding: 0 0px;\n}");
    });

    it("lets the wallpaper show through", () => {
      expect(fixtureBuild.file("waybar/dark/borderless/colors.css")).toContain(
        "@define-color component_bar_style_borderless_background rgba(0, 0, 0, 0);",
      );
    });

    it("draws no outline, no corner and no inset", () => {
      expect(borderlessBox()).toMatch(/border: 0px solid [^;]+;\n {2}border-radius: 0px;\n {2}padding: 0px;/);
    });

    it("keeps the bar layout of the floating bar", () => {
      expect(borderlessConfig()["modules-right"]).toEqual(config()["modules-right"]);
    });
  });

  describe("image modules", () => {
    const borderlessStyle = () => fixtureBuild.file("waybar/dark/borderless/style.css");
    const borderlessSettings = () => JSON.parse(fixtureBuild.file("waybar/dark/borderless/settings.json"));

    it("leaves a group out of the styles it does not name", () => {
      expect(config()["modules-left"]).not.toContain("custom/logo");
    });

    it("shows a group in the styles it names", () => {
      expect(borderlessSettings()["modules-left"]).toEqual(["custom/logo", "hyprland/workspaces"]);
    });

    it("tints the image in the borderless bar's desktop text colour", () => {
      expect(fixtureBuild.file("waybar/dark/borderless/logo.svg")).toContain('<svg color="rgba(255, 255, 255, 0.5)" ');
    });

    it("draws the image as tall as the bar's type size, keeping its aspect ratio", () => {
      expect(borderlessStyle()).toMatch(/#custom-logo \{\n {2}min-width: 16px;\n {2}background-image: url\("logo\.svg"\);\n {2}background-size: 16px 8px;/);
    });

    it("pins the image to the module's left edge", () => {
      expect(borderlessStyle()).toMatch(/#custom-logo \{[^}]*background-position: left center;/);
    });

    it("gives the image no marker padding, so it sits on the window edge", () => {
      expect(borderlessStyle()).not.toMatch(/#custom-logo[^{]*\{\n {2}padding/);
    });

    it("sets an image one cell from the next group, the gutter between windows", () => {
      expect(borderlessStyle()).toContain("#custom-logo {\n  margin-right: 5px;\n}");
    });

    it("keeps the image module's static format", () => {
      expect(borderlessSettings()["custom/logo"]).toEqual({ format: "" });
    });
  });
});
